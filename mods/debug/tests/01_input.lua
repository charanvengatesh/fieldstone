-- Injected input reaches the engine like a player's: keys move the player, scrolling
-- picks hotbar slots, and the readouts agree.

test("a held key walks the player and lets go cleanly", function()
    local x0, y0 = player_pos()
    press_key("W")
    wait(1)
    expect(key_pressed("W"), "W reads as held the frame after it was pressed")
    wait(60)
    release_key("W")
    wait(2)
    expect(not key_pressed("W"), "W reads as released")
    local x1, y1 = player_pos()
    local moved = math.sqrt((x1 - x0) ^ 2 + (y1 - y0) ^ 2)
    expect(moved > 1.5, string.format("the player walked %.2f blocks", moved))
    expect(wait_until(is_grounded, 120), "the player came to rest on the ground")
end)

test("a tapped key is just pressed for one frame", function()
    press_key("K")
    wait(1)
    expect(key_just_pressed("K"), "just pressed on the first frame")
    wait(1)
    expect(key_pressed("K") and not key_just_pressed("K"), "held, not just pressed, after that")
    release_key("K")
    wait(1)
end)

test("scrolling steps the hotbar and mouse buttons read back", function()
    local slot = selected_slot()
    scroll(-1)
    wait(2)
    expect(selected_slot() == slot % 10 + 1, "scrolling down picks the next slot")
    scroll(1)
    wait(2)
    expect(selected_slot() == slot, "scrolling up comes back")
    press_mouse("middle")
    wait(1)
    expect(mouse_pressed("middle"), "the middle button reads as held")
    release_mouse("middle")
    wait(1)
    expect(not mouse_pressed("middle"), "and as released")
end)
